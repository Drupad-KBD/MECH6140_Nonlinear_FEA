classdef Quad8 < fea.elements.ElementBase
    % Eight-node serendipity element, 3x3 full Gauss integration.
    % Node order: four corners counterclockwise, then mid-edge 1-2,2-3,3-4,4-1.
    methods
        function obj=Quad8(X,material,thickness)
            obj@fea.elements.ElementBase(X,material,thickness,8,3);
        end
        function [N,dN]=ShapeFunctions(~,xi)
            r=xi(1); s=xi(2);
            N=[-.25*(1-r)*(1-s)*(1+r+s), ...
               -.25*(1+r)*(1-s)*(1-r+s), ...
               -.25*(1+r)*(1+s)*(1-r-s), ...
               -.25*(1-r)*(1+s)*(1+r-s), ...
                .5*(1-r^2)*(1-s), ...
                .5*(1+r)*(1-s^2), ...
                .5*(1-r^2)*(1+s), ...
                .5*(1-r)*(1-s^2)];
            dr=[.25*(1-s)*(2*r+s), ...
                .25*(1-s)*(2*r-s), ...
                .25*(1+s)*(2*r+s), ...
                .25*(1+s)*(2*r-s), ...
                -r*(1-s), ...
                .5*(1-s^2), ...
                -r*(1+s), ...
                -.5*(1-s^2)];
            ds=[.25*(1-r)*(r+2*s), ...
                .25*(1+r)*(-r+2*s), ...
                .25*(1+r)*(r+2*s), ...
                .25*(1-r)*(-r+2*s), ...
                -.5*(1-r^2), ...
                -(1+r)*s, ...
                .5*(1-r^2), ...
                -(1-r)*s];
            dN=[dr;ds];
        end
    end
end
