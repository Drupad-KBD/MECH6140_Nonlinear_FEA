function [f_int_GP] = Internal_Force_GP_cal( ...
    B,S, ...
    ShapeFun_selection, ...
    xi_cordi_4N, ...
    x_cap, ...
    weight, ...
    thickness)

%% ================================================================
% Internal Force Contribution at One Gauss Point
% Total Lagrangian Formulation
% ================================================================

%% Second Piola-Kirchhoff stress vector
%
% S_vec = [S11
%          S22
%          S12]

S_vec = [ ...
    S(1,1);
    S(2,2);
    S(1,2)];


%% Reference Jacobian determinant
%
% dV0 = thickness * det(J0) * dxi * deta

J_det = ...
    Det_Jacobian_cal( ...
    ShapeFun_selection, ...
    xi_cordi_4N, ...
    x_cap);


%% Internal force contribution
%
% f_int_GP =
% B' * S_vec * thickness * det(J0) * weight

f_int_GP = ...
    B.' ...
    * S_vec ...
    * thickness ...
    * J_det ...
    * weight;

end