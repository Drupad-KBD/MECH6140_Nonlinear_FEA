function [U] = Total_Strain_Energy_cal( ...
    q, ...
    Nodal_Locations, ...
    ShapeFun_derivative, ...
    lambda_L,mu, ...
    thickness)

%% ================================================================
% Total Element Strain Energy
%
% U = integral(W dV0)
% ================================================================

x_cap = ...
    X_2_to_X_1converter( ...
    Nodal_Locations);

[gp,w] = ...
    gauss_location_weight(2);

U = 0;


%% ================================================================
% Gauss integration
% ================================================================

for i = 1:2

    for j = 1:2

        xi = [ ...
            gp(i), ...
            gp(j)];

        weight = ...
            w(i)*w(j);


        %% Displacement gradient

        H = ...
            Displacement_Gradient_cal( ...
            ShapeFun_derivative, ...
            xi, ...
            x_cap, ...
            q);


        %% Green-Lagrange strain

        [E_GL,~] = ...
            Green_Lagrange_Strain_cal(H);


        %% Strain energy density

        W = ...
            Strain_Energy_Density_cal( ...
            E_GL, ...
            lambda_L, ...
            mu);


        %% Reference Jacobian determinant

        det_J0 = ...
            Det_Jacobian_cal( ...
            ShapeFun_derivative, ...
            xi, ...
            x_cap);


        %% Total strain energy

        U = ...
            U ...
            + W ...
            * thickness ...
            * det_J0 ...
            * weight;

    end

end

end